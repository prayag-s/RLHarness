def load_bundle_context(bundle_dir: Path):
    model_path = bundle_dir / "model.onnx"
    baseline_path = bundle_dir / "drift_baseline.json"
    config_json_path = bundle_dir / "task_config.json"

    if not model_path.exists():
        raise FileNotFoundError(f"Model missing: {model_path}")

    sess = ort.InferenceSession(str(model_path))

    baseline_data = {}
    if baseline_path.exists():
        with open(baseline_path, "r", encoding="utf-8") as f:
            baseline_data = json.load(f)

    action_labels = []
    if config_json_path.exists():
        try:
            with open(config_json_path, "r", encoding="utf-8") as f:
                cfg = json.load(f)
                action_labels = cfg.get("adapter_config", {}).get("action_labels", [])
        except Exception:
            pass

    return sess, baseline_data, action_labels


def execute_inference(
    sess: ort.InferenceSession,
    baseline_data: dict[str, Any],
    action_labels: list[str],
    obs_batch: np.ndarray,
) -> dict[str, Any]:
    if obs_batch.ndim == 1:
        obs_batch = np.expand_dims(obs_batch, axis=0)

    obs_batch = obs_batch.astype(np.float32)
    probs = sess.run(None, {"obs": obs_batch})[0]
    predicted_actions = np.argmax(probs, axis=-1)

    predictions = []
    for idx, (p, a) in enumerate(zip(probs, predicted_actions)):
        lbl = action_labels[a] if a < len(action_labels) else f"action_{a}"
        predictions.append({
            "sample_idx": idx,
            "action_idx": int(a),
            "action_label": lbl,
            "probabilities": [round(float(val), 4) for val in p],
        })

    # Unsupervised Drift Telemetry
    feature_names = baseline_data.get("feature_names", [])
    quantiles = baseline_data.get("quantiles_per_feature", {})
    psi_vals: dict[str, float] = {}
    for f_idx, fname in enumerate(feature_names[:obs_batch.shape[1]]):
        edges = quantiles.get(fname)
        if edges and len(edges) == 11:
            col = obs_batch[:, f_idx]
            counts, _ = np.histogram(col, bins=edges)
            p = np.maximum(counts / max(1, len(obs_batch)), 1e-4)
            p = p / np.sum(p)
            q = np.full(10, 0.10)
            psi = float(np.sum((p - q) * np.log(p / q)))
            psi_vals[fname] = round(psi, 4)

    max_psi = max(psi_vals.values()) if psi_vals else 0.0

    ent = -np.sum(probs * np.log(np.maximum(probs, 1e-8)), axis=-1)
    mean_ent = float(np.mean(ent))
    ent_mean_base = baseline_data.get("entropy_mean", 0.25)
    ent_std_base = baseline_data.get("entropy_std", 0.08)
    ent_z = abs(mean_ent - ent_mean_base) / max(ent_std_base, 1e-4)

    is_drifted = bool((max_psi > 0.25) or (ent_z > 2.5))

    return {
        "predictions": predictions,
        "drift": {
            "is_drifted": is_drifted,
            "max_psi": round(max_psi, 4),
            "entropy_zscore": round(float(ent_z), 2),
            "feature_psis": psi_vals,
            "status": "DRIFT_DETECTED" if is_drifted else "HEALTHY",
        },
    }


def print_cli_summary(res: dict[str, Any], total_samples: int):
    predictions = res["predictions"]
    drift = res["drift"]

    print(f"\\n=== Local Policy Inference Results ({total_samples} samples) ===")
    for p in predictions[:5]:
        print(f"Sample #{p['sample_idx']+1:02d}: Action={p['action_idx']} ({p['action_label']}) | Probs={p['probabilities']}")
    if len(predictions) > 5:
        print(f"... and {len(predictions) - 5} more samples.")

    print("\\n=== Unsupervised Drift Telemetry ===")
    print(f"Max Feature PSI: {drift['max_psi']:.4f} (Threshold: 0.25)")
    print(f"Policy Entropy Z-score: {drift['entropy_zscore']:.2f} (Threshold: 2.5)")
    status_tag = "[ALERT: DRIFT DETECTED]" if drift["is_drifted"] else "[HEALTHY: NO DRIFT]"
    print(f"Drift Status: {status_tag}")


class PolicyDaemonHandler(http.server.BaseHTTPRequestHandler):
    def log_message(self, format, *args):
        # Quiet logger for minimal overhead
        pass

    def do_GET(self):
        if self.path in ("/", "/health", "/info"):
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.end_headers()
            resp = {
                "status": "ok",
                "service": "RL-Native Agent Policy Daemon",
                "bundle_dir": str(self.server.bundle_dir.name),
                "action_labels": self.server.action_labels,
                "feature_count": len(self.server.baseline_data.get("feature_names", [])),
            }
            self.wfile.write(json.dumps(resp).encode("utf-8"))
        else:
            self.send_response(404)
            self.end_headers()

    def do_POST(self):
        if self.path == "/predict":
            content_len = int(self.headers.get("Content-Length", 0))
            body = self.rfile.read(content_len).decode("utf-8")
            try:
                data = json.loads(body)
                if "observations" in data:
                    obs = np.array(data["observations"], dtype=np.float32)
                elif "observation" in data:
                    obs = np.array(data["observation"], dtype=np.float32)
                else:
                    self.send_response(400)
                    self.send_header("Content-Type", "application/json")
                    self.end_headers()
                    self.wfile.write(json.dumps({"error": "Missing 'observations' or 'observation' key"}).encode("utf-8"))
                    return

                res = execute_inference(
                    self.server.sess,
                    self.server.baseline_data,
                    self.server.action_labels,
                    obs,
                )
                self.send_response(200)
                self.send_header("Content-Type", "application/json")
                self.end_headers()
                self.wfile.write(json.dumps(res).encode("utf-8"))
            except Exception as e:
                self.send_response(500)
                self.send_header("Content-Type", "application/json")
                self.end_headers()
                self.wfile.write(json.dumps({"error": str(e)}).encode("utf-8"))
        elif self.path == "/shutdown":
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.end_headers()
            self.wfile.write(json.dumps({"status": "shutting_down"}).encode("utf-8"))
            threading.Thread(target=self.server.shutdown).start()
        else:
            self.send_response(404)
            self.end_headers()


def run_daemon(bundle_dir: Path, host: str, port: int):
    sess, baseline_data, action_labels = load_bundle_context(bundle_dir)
    server = http.server.HTTPServer((host, port), PolicyDaemonHandler)
    server.bundle_dir = bundle_dir
    server.sess = sess
    server.baseline_data = baseline_data
    server.action_labels = action_labels

    print(f"Starting Policy Daemon on http://{host}:{port} ...")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\\nShutting down daemon.")
    finally:
        server.server_close()


