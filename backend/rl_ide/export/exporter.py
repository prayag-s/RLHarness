        # 1b. Behavioural parity: the shipped artefact must behave like the trained policy,
        # not merely compute the same numbers on random observations.
        deployment: dict[str, Any] = {}
        if model is not None:
            try:
                from rl_ide.autopilot.sandbox_runner import behavioural_parity_in_sandbox
                from rl_ide.security import SandboxUnavailable

                parity_zip = bundle_dir / "_parity_model.zip"
                try:
                    model.save(str(parity_zip))
                    deployment = behavioural_parity_in_sandbox(
                        env_module_path,
                        model_path=parity_zip,
                        onnx_path=onnx_file,
                        records=records,
                    )
                except SandboxUnavailable:
                    env_cls = load_synthesized_env_class(env_module_path)
                    sample_env = instantiate_env(env_cls, dataset_records=records)
                    deployment = cls.verify_behavioural_parity(
                        model=model, onnx_path=onnx_file, env=sample_env
                    )
            except Exception as behaviour_err:
                deployment = {"error": f"behavioural parity unavailable: {behaviour_err}"}
            finally:
                try:
                    (bundle_dir / "_parity_model.zip").unlink(missing_ok=True)
                except OSError:
                    pass

        scorecard_payload: dict[str, Any] = dict(scorecard) if scorecard else {
            "version": 1,
            "notes": ["No training scorecard was available for this session."],
        }
        scorecard_payload["deployment"] = {
            **deployment,
            "onnx_numeric_parity_max_diff": float(max_diff),
            "onnx_numeric_parity_tolerance": ONNX_PARITY_TOLERANCE,
            "contains_training_data": bool(include_data),
        }
        (bundle_dir / "scorecard.json").write_text(
            json.dumps(scorecard_payload, indent=2), encoding="utf-8"
        )

        # 2. Save blueprint_spec.json and the executable safety rules.
        (bundle_dir / "blueprint_spec.json").write_text(
            blueprint.model_dump_json(indent=2), encoding="utf-8"
        )
        safety_rules = [
            c.model_dump() if hasattr(c, "model_dump") else dict(c)
            for c in (getattr(blueprint, "hard_constraints", []) or [])
        ]
        (bundle_dir / "safety_rules.json").write_text(
            json.dumps(safety_rules, indent=2), encoding="utf-8"
        )

        # 3. Copy env_module.py and arena.html. Customer rows are NOT shipped by default: the
        # generated module embeds a 120-row sample, which is fine for a local studio and wrong for
        # a bundle that gets emailed around. `include_data=True` is the explicit opt-in.
        env_src = Path(env_module_path)
        data_dir = bundle_dir / "data"
        data_dir.mkdir(parents=True, exist_ok=True)
        if env_src.exists():
            env_text = env_src.read_text(encoding="utf-8")
            if not include_data:
                env_text = re.sub(
                    r"^    _records = .*$",
                    "    _records = []  # stripped: customer rows are not shipped by default (G3)",
                    env_text,
                    count=1,
                    flags=re.MULTILINE,
                )
                (data_dir / "README.md").write_text(
                    "# Training data not included\n\n"
                    "This bundle was exported without customer rows. The ONNX policy runs on the\n"
                    "observations you supply, so no data is required for inference.\n\n"
                    "To reproduce the environment locally, place a `records.json` file here\n"
                    "(a JSON list of row objects shaped like the training data) and instantiate\n"
                    "`SynthesizedGymEnv(dataset_records=<rows>)`.\n\n"
                    "Re-export with `include_data: true` if you explicitly want the sample\n"
                    "embedded in the bundle.\n\n"
                    "If this bundle contains `safety_rules.json`, the supported runtime\n"
                    "(`run_local.py`) requires `--record-json` so the hard-constraint mask can be\n"
                    "applied. It refuses to run blind rather than emit an unconstrained decision.\n",
                    encoding="utf-8",
                )
            (bundle_dir / "env_module.py").write_text(env_text, encoding="utf-8")

        arena_src = Path(arena_html_path)
        if arena_src.exists():
            shutil.copy2(str(arena_src), str(bundle_dir / "arena.html"))

        # 4. Generate drift baseline fitted on the realistic observations captured above
        from rl_ide.contracts.adapter import EpisodeLog, StepResult

        if not real_obs_samples:
            real_obs_samples = [[0.0] * obs_dim for _ in range(10)]

        dummy_episodes = []
        chunk_size = max(1, len(real_obs_samples) // 5)
        for ep_i in range(5):
            chunk = real_obs_samples[ep_i * chunk_size : (ep_i + 1) * chunk_size]
            steps = [
                StepResult(
                    obs_vector=o if len(o) == obs_dim else (o[:obs_dim] if len(o) > obs_dim else o + [0.0]*(obs_dim - len(o))),
                    events={"action": {"action_idx": 0}},
                    terminated=False,
                    truncated=False,
                )
                for o in chunk
            ]
            dummy_episodes.append(EpisodeLog(episode_id=ep_i, steps=steps))

        feature_names = list(blueprint.observation_features)
        if len(feature_names) < obs_dim:
            feature_names = feature_names + [f"feature_{i}" for i in range(len(feature_names), obs_dim)]
        elif len(feature_names) > obs_dim:
            feature_names = feature_names[:obs_dim]

        baseline = DriftDetector.fit_baseline(
            episodes=dummy_episodes,
            feature_names=feature_names,
        )
        baseline.save(bundle_dir / "drift_baseline.json")

        # 5. Generate standalone run_local.py
        run_local_file = bundle_dir / "run_local.py"
        run_local_file.write_text(STANDALONE_RUN_LOCAL_TEMPLATE, encoding="utf-8")
        run_local_file.chmod(0o755)

        # 6. Package as ZIP archive
        zip_path = out_dir / f"{b_name}.zip"
        with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zip_f:
            for root, _, files in shutil.os.walk(bundle_dir):
                for file in files:
                    file_path = Path(root) / file
                    arc_name = file_path.relative_to(bundle_dir.parent)
                    zip_f.write(file_path, arc_name)

        return bundle_dir, zip_path, max_diff
