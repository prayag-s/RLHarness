def load_bundle_context(bundle_dir: Path):
    model_path = bundle_dir / "model.onnx"
    baseline_path = bundle_dir / "drift_baseline.json"
    spec_path = bundle_dir / "blueprint_spec.json"
    config_json_path = bundle_dir / "task_config.json"

    if not model_path.exists():
        raise FileNotFoundError(f"Model missing: {model_path}")

    sess = ort.InferenceSession(str(model_path))

    baseline_data = {}
    if baseline_path.exists():
        with open(baseline_path, "r", encoding="utf-8") as f:
            baseline_data = json.load(f)

    action_labels = []
    if spec_path.exists():
        try:
            with open(spec_path, "r", encoding="utf-8") as f:
                spec = json.load(f)
                action_labels = spec.get("action_labels", [])
        except Exception:
            pass
    elif config_json_path.exists():
        try:
            with open(config_json_path, "r", encoding="utf-8") as f:
                cfg = json.load(f)
                action_labels = cfg.get("adapter_config", {}).get("action_labels", [])
        except Exception:
            pass

    return sess, baseline_data, action_labels


def execute_inference(
    sess: ort.InferenceSession,
    baseline_data: dict[str, Any],
    action_labels: list[str],
    obs_batch: np.ndarray,
) -> dict[str, Any]:
    if obs_batch.ndim == 1:
        obs_batch = np.expand_dims(obs_batch, axis=0)

    obs_batch = obs_batch.astype(np.float32)
    try:
        expected_dim = sess.get_inputs()[0].shape[1]
        if isinstance(expected_dim, int) and obs_batch.shape[1] != expected_dim:
            if obs_batch.shape[1] < expected_dim:
                pad = np.zeros((obs_batch.shape[0], expected_dim - obs_batch.shape[1]), dtype=np.float32)
                obs_batch = np.hstack([obs_batch, pad])
            else:
                obs_batch = obs_batch[:, :expected_dim]
    except Exception:
        pass

    probs = sess.run(None, {"obs": obs_batch})[0]
    predicted_actions = np.argmax(probs, axis=-1)

    predictions = []
    for idx, (p, a) in enumerate(zip(probs, predicted_actions)):
        lbl = action_labels[a] if a < len(action_labels) else f"action_{a}"
        predictions.append({
            "sample_idx": idx,
            "action_idx": int(a),
            "action_label": lbl,
            "probabilities": [float(val) for val in p],
        })

    # Basic drift check on inference batch
    drift_report = {"drift_detected": False, "psi_max": 0.0, "status": "healthy"}
    if baseline_data and "quantile_boundaries" in baseline_data:
        try:
            from rl_ide.drift.monitor import DriftDetector, DriftBaseline
            detector = DriftDetector(DriftBaseline.load(baseline_data))
            sig = detector.detect_drift(obs_batch, probs, predicted_actions)
            drift_report = {
                "drift_detected": sig.drift_detected,
                "psi_max": sig.feature_psi_max,
                "status": sig.severity,
            }
        except Exception:
            pass

    return {
        "predictions": predictions,
        "drift": drift_report,
        "batch_size": len(obs_batch),
    }


def print_cli_summary(res: dict[str, Any], n_samples: int):
    print("=" * 60)
    print(f"RL Policy Local Inference Complete: {n_samples} samples processed")
    print("=" * 60)
    print(f"Drift Status: {res.get('drift', {}).get('status', 'healthy').upper()} (PSI Max: {res.get('drift', {}).get('psi_max', 0.0):.3f})")
    print("-" * 60)
    print("Sample Predictions:")
    for pred in res["predictions"][:5]:
        print(f"  [#{pred['sample_idx']}] Action: {pred['action_label']} ({pred['action_idx']}) | Probs: {[round(x, 3) for x in pred['probabilities']]}")
    if len(res["predictions"]) > 5:
        print(f"  ... and {len(res['predictions']) - 5} more.")
    print("=" * 60)


class PolicyDaemonHandler(http.server.BaseHTTPRequestHandler):
    def do_GET(self):
        if self.path == "/health":
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.end_headers()
            self.wfile.write(json.dumps({"status": "healthy", "service": "v4.0 policy-daemon"}).encode("utf-8"))
        elif self.path == "/info":
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.end_headers()
            self.wfile.write(json.dumps({
                "action_labels": self.server.action_labels,
                "has_baseline": bool(self.server.baseline_data),
            }).encode("utf-8"))
        else:
            self.send_response(404)
            self.end_headers()

    def do_POST(self):
        if self.path == "/predict":
            content_len = int(self.headers.get("Content-Length", 0))
            body = self.rfile.read(content_len).decode("utf-8")
            try:
                data = json.loads(body)
                if "observations" in data:
                    obs = np.array(data["observations"], dtype=np.float32)
                elif "observation" in data:
                    obs = np.array(data["observation"], dtype=np.float32)
                else:
                    self.send_response(400)
                    self.send_header("Content-Type", "application/json")
                    self.end_headers()
                    self.wfile.write(json.dumps({"error": "Missing 'observations' or 'observation' key"}).encode("utf-8"))
                    return

                res = execute_inference(
                    self.server.sess,
                    self.server.baseline_data,
                    self.server.action_labels,
                    obs,
                )
                self.send_response(200)
                self.send_header("Content-Type", "application/json")
                self.end_headers()
                self.wfile.write(json.dumps(res).encode("utf-8"))
            except Exception as e:
                self.send_response(500)
                self.send_header("Content-Type", "application/json")
                self.end_headers()
                self.wfile.write(json.dumps({"error": str(e)}).encode("utf-8"))
        elif self.path == "/shutdown":
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.end_headers()
            self.wfile.write(json.dumps({"status": "shutting_down"}).encode("utf-8"))
            threading.Thread(target=self.server.shutdown).start()
        else:
            self.send_response(404)
            self.end_headers()


def run_daemon(bundle_dir: Path, host: str, port: int):
    sess, baseline_data, action_labels = load_bundle_context(bundle_dir)
    server = http.server.HTTPServer((host, port), PolicyDaemonHandler)
    server.bundle_dir = bundle_dir
    server.sess = sess
    server.baseline_data = baseline_data
    server.action_labels = action_labels

    print(f"Starting Policy Daemon on http://{host}:{port} ...")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\\nShutting down daemon.")
    finally:
        server.server_close()


