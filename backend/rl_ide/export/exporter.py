ONNX_PARITY_TOLERANCE = 1e-5


class PolicyExporter:
    """Exports SB3 PPO policies to ONNX, performs parity checking, and packages self-contained run bundles."""

    @classmethod
    def export_onnx(
        cls,
        model: PPO,
        output_path: str | Path,
        obs_dim: int,
        opset_version: int = 17,
    ) -> Path:
        """Exports the trained policy actor to ONNX format."""
        out_p = Path(output_path).resolve()
        out_p.parent.mkdir(parents=True, exist_ok=True)

        policy = model.policy
        orig_device = getattr(policy, "device", None)
        policy.to("cpu")
        wrapper = _OnnxActorWrapper(policy)
        wrapper.eval()

        dummy_input = torch.randn(1, obs_dim, dtype=torch.float32, device="cpu")

        torch.onnx.export(
            wrapper,
            dummy_input,
            str(out_p),
            opset_version=opset_version,
            input_names=["obs"],
            output_names=["probs"],
            dynamic_axes={"obs": {0: "batch_size"}, "probs": {0: "batch_size"}},
            dynamo=False,
        )

        if orig_device is not None:
            policy.to(orig_device)

        return out_p

    @classmethod
    def verify_parity(
        cls,
        model: PPO,
        onnx_path: str | Path,
        obs_dim: int,
        n_samples: int = 32,
        sample_obs: np.ndarray | None = None,
    ) -> float:
        """Verifies numerical parity between PyTorch policy and ONNX Runtime session.

        Parity is measured on real environment observations when available, at the documented
        ``< 1e-5`` tolerance.
        """
        orig_device = getattr(model.policy, "device", None)
        model.policy.to("cpu")
        wrapper = _OnnxActorWrapper(model.policy)
        wrapper.eval()

        if sample_obs is not None and len(sample_obs) > 0:
            test_obs = np.asarray(sample_obs, dtype=np.float32)
            if test_obs.ndim == 1:
                test_obs = test_obs.reshape(1, -1)
            if test_obs.shape[1] < obs_dim:
                test_obs = np.pad(test_obs, ((0, 0), (0, obs_dim - test_obs.shape[1])))
            test_obs = test_obs[:, :obs_dim]
        else:
            test_obs = np.random.randn(n_samples, obs_dim).astype(np.float32)
        test_obs_tensor = torch.from_numpy(test_obs)

        with torch.no_grad():
            pytorch_probs = wrapper(test_obs_tensor).cpu().numpy()

        if orig_device is not None:
            model.policy.to(orig_device)

        sess = ort.InferenceSession(str(onnx_path))
        onnx_probs = sess.run(None, {"obs": test_obs})[0]

        max_diff = float(np.max(np.abs(pytorch_probs - onnx_probs)))
        if not np.allclose(pytorch_probs, onnx_probs, atol=ONNX_PARITY_TOLERANCE):
            raise ValueError(
                f"ONNX parity check failed! Max diff: {max_diff:.3e} exceeds {ONNX_PARITY_TOLERANCE}"
            )

        return max_diff

    @classmethod
    def package_runbundle(
        cls,
        session_id: str,
        blueprint: AgentBlueprintSpec,
        model: PPO,
        env_module_path: Path | str,
        arena_html_path: Path | str,
        output_dir: str | Path = "exported_bundles",
        bundle_name: str | None = None,
    ) -> tuple[Path, Path, float]:
        """Creates a standalone .runbundle directory and zip archive."""
        out_dir = Path(output_dir).resolve()
        out_dir.mkdir(parents=True, exist_ok=True)

        missing = [str(p) for p in (env_module_path, arena_html_path) if not Path(p).exists()]
        if missing:
            # Never return a "successful" bundle that cannot be executed.
            raise FileNotFoundError(
                "Cannot package runbundle; missing required artefacts: " + ", ".join(missing)
            )

        b_name = bundle_name or f"{session_id}.runbundle"
        bundle_dir = out_dir / b_name
        bundle_dir.mkdir(parents=True, exist_ok=True)

        # 1. Export ONNX and verify numerical parity (< 1e-5)
        onnx_file = bundle_dir / "model.onnx"
        if model is not None and hasattr(model, "observation_space") and hasattr(model.observation_space, "shape") and model.observation_space.shape:
            obs_dim = int(model.observation_space.shape[0])
        elif model is not None and hasattr(model, "policy") and hasattr(model.policy, "observation_space") and hasattr(model.policy.observation_space, "shape") and model.policy.observation_space.shape:
            obs_dim = int(model.policy.observation_space.shape[0])
        else:
            obs_dim = len(blueprint.observation_features)

        # Collect realistic observations from the packaged environment (used for parity + drift).
        from rl_ide.synthesizer.env_builder import load_synthesized_env_class, instantiate_env
        from rl_ide.state.records_store import load_records

        real_obs_samples: list[list[float]] = []
        try:
            env_cls = load_synthesized_env_class(env_module_path)
            sample_env = instantiate_env(env_cls, dataset_records=load_records(Path(env_module_path).parent))
            for _ in range(5):
                o, _ = sample_env.reset()
                real_obs_samples.append([float(x) for x in o])
                for _ in range(10):
                    o, _, term, trunc, _ = sample_env.step(sample_env.action_space.sample())
                    real_obs_samples.append([float(x) for x in o])
                    if term or trunc:
                        break
        except Exception:
            real_obs_samples = []

        parity_obs = np.asarray(real_obs_samples, dtype=np.float32) if real_obs_samples else None

        orig_device = getattr(model.policy, "device", None) if model and hasattr(model, "policy") else None
        if model and hasattr(model, "policy"):
            model.policy.to("cpu")
        try:
            cls.export_onnx(model=model, output_path=onnx_file, obs_dim=obs_dim)
            max_diff = cls.verify_parity(
                model=model, onnx_path=onnx_file, obs_dim=obs_dim, sample_obs=parity_obs
            )
        finally:
            if orig_device is not None and model and hasattr(model, "policy"):
                model.policy.to(orig_device)

        # 2. Save blueprint_spec.json
        (bundle_dir / "blueprint_spec.json").write_text(
            blueprint.model_dump_json(indent=2), encoding="utf-8"
        )

        # 3. Copy env_module.py and arena.html
        env_src = Path(env_module_path)
        if env_src.exists():
            shutil.copy2(str(env_src), str(bundle_dir / "env_module.py"))

        arena_src = Path(arena_html_path)
        if arena_src.exists():
            shutil.copy2(str(arena_src), str(bundle_dir / "arena.html"))

        # 4. Generate drift baseline fitted on the realistic observations captured above
        from rl_ide.contracts.adapter import EpisodeLog, StepResult

        if not real_obs_samples:
            real_obs_samples = [[0.0] * obs_dim for _ in range(10)]

        dummy_episodes = []
        chunk_size = max(1, len(real_obs_samples) // 5)
        for ep_i in range(5):
            chunk = real_obs_samples[ep_i * chunk_size : (ep_i + 1) * chunk_size]
            steps = [
                StepResult(
                    obs_vector=o if len(o) == obs_dim else (o[:obs_dim] if len(o) > obs_dim else o + [0.0]*(obs_dim - len(o))),
                    events={"action": {"action_idx": 0}},
                    terminated=False,
                    truncated=False,
                )
                for o in chunk
            ]
            dummy_episodes.append(EpisodeLog(episode_id=ep_i, steps=steps))

        feature_names = list(blueprint.observation_features)
        if len(feature_names) < obs_dim:
            feature_names = feature_names + [f"feature_{i}" for i in range(len(feature_names), obs_dim)]
        elif len(feature_names) > obs_dim:
            feature_names = feature_names[:obs_dim]

        baseline = DriftDetector.fit_baseline(
            episodes=dummy_episodes,
            feature_names=feature_names,
        )
        baseline.save(bundle_dir / "drift_baseline.json")

        # 5. Generate standalone run_local.py
        run_local_file = bundle_dir / "run_local.py"
        run_local_file.write_text(STANDALONE_RUN_LOCAL_TEMPLATE, encoding="utf-8")
        run_local_file.chmod(0o755)

        # 6. Package as ZIP archive
        zip_path = out_dir / f"{b_name}.zip"
        with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zip_f:
            for root, _, files in shutil.os.walk(bundle_dir):
                for file in files:
                    file_path = Path(root) / file
                    arc_name = file_path.relative_to(bundle_dir.parent)
                    zip_f.write(file_path, arc_name)

        return bundle_dir, zip_path, max_diff
