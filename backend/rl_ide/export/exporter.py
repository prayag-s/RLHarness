class PolicyExporter:
    """Exports SB3 PPO policies to ONNX, performs parity checking, and packages self-contained run bundles."""

    @classmethod
    def export_onnx(
        cls,
        model: PPO,
        output_path: str | Path,
        obs_dim: int,
        opset_version: int = 17,
    ) -> Path:
        """Exports the trained policy actor to ONNX format."""
        out_p = Path(output_path).resolve()
        out_p.parent.mkdir(parents=True, exist_ok=True)

        policy = model.policy
        wrapper = _OnnxActorWrapper(policy)
        wrapper.eval()

        dummy_input = torch.randn(1, obs_dim, dtype=torch.float32, device="cpu")

        torch.onnx.export(
            wrapper,
            dummy_input,
            str(out_p),
            opset_version=opset_version,
            input_names=["obs"],
            output_names=["probs"],
            dynamic_axes={"obs": {0: "batch_size"}, "probs": {0: "batch_size"}},
            dynamo=False,
        )

        return out_p

    @classmethod
    def verify_parity(
        cls,
        model: PPO,
        onnx_path: str | Path,
        obs_dim: int,
        n_samples: int = 32,
    ) -> float:
        """Verifies numerical parity between PyTorch policy and ONNX Runtime session."""
        wrapper = _OnnxActorWrapper(model.policy)
        wrapper.eval()

        test_obs = np.random.randn(n_samples, obs_dim).astype(np.float32)
        test_obs_tensor = torch.from_numpy(test_obs)

        with torch.no_grad():
            pytorch_probs = wrapper(test_obs_tensor).cpu().numpy()

        sess = ort.InferenceSession(str(onnx_path))
        onnx_probs = sess.run(None, {"obs": test_obs})[0]

        max_diff = float(np.max(np.abs(pytorch_probs - onnx_probs)))
        if not np.allclose(pytorch_probs, onnx_probs, atol=1e-5):
            raise ValueError(f"ONNX parity check failed! Max diff: {max_diff:.3e} exceeds 1e-5")

        return max_diff

    @classmethod
    def create_runbundle(
        cls,
        task_config: TaskConfig,
        reward_dsl: RewardDSL,
        model: PPO,
        episodes: list[EpisodeLog],
        output_dir: str | Path = "exported_bundles",
        bundle_name: str | None = None,
    ) -> tuple[Path, Path, float]:
        """Creates a standalone .runbundle directory and zip archive."""
        out_dir = Path(output_dir).resolve()
        out_dir.mkdir(parents=True, exist_ok=True)

        b_name = bundle_name or f"{task_config.task_id}_bundle"
        bundle_dir = out_dir / f"{b_name}.runbundle"
        bundle_dir.mkdir(parents=True, exist_ok=True)

        # 1. Export ONNX and verify parity
        onnx_file = bundle_dir / "model.onnx"
        obs_dim = model.observation_space.shape[0]
        cls.export_onnx(model=model, output_path=onnx_file, obs_dim=obs_dim)
        max_diff = cls.verify_parity(model=model, onnx_path=onnx_file, obs_dim=obs_dim)

        # 2. Save task configs in both YAML and JSON for zero-dependency parsing
        (bundle_dir / "task_config.yaml").write_text(task_config.to_yaml(), encoding="utf-8")
        (bundle_dir / "task_config.json").write_text(json.dumps(task_config.model_dump(), indent=2), encoding="utf-8")
        (bundle_dir / "reward_dsl.yaml").write_text(reward_dsl.to_yaml(), encoding="utf-8")

        # 3. Fit and save drift baseline
        feature_names = (
            task_config.adapter_config.get("feature_names")
            or [f"feature_{i}" for i in range(obs_dim)]
        )
        baseline = DriftDetector.fit_baseline(episodes=episodes, feature_names=feature_names)
        baseline.save(bundle_dir / "drift_baseline.json")

        # 4. Generate standalone run_local.py with CLI and --serve HTTP daemon
        run_local_file = bundle_dir / "run_local.py"
        run_local_file.write_text(STANDALONE_RUN_LOCAL_TEMPLATE, encoding="utf-8")
        run_local_file.chmod(0o755)

        # 5. Package as ZIP archive
        zip_path = out_dir / f"{b_name}.runbundle.zip"
        with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zip_f:
            for root, _, files in shutil.os.walk(bundle_dir):
                for file in files:
                    file_path = Path(root) / file
                    arc_name = file_path.relative_to(bundle_dir.parent)
                    zip_f.write(file_path, arc_name)

        return bundle_dir, zip_path, max_diff
