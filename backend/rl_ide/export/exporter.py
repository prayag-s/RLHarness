def _rule_matches(record: dict[str, Any], rule: dict[str, Any]) -> bool:
    raw = record.get(rule.get("feature"))
    if raw is None:
        return False
    try:
        left = float(raw)
        right = float(rule.get("value"))
    except (TypeError, ValueError):
        return str(raw).strip().lower() == str(rule.get("value")).strip().lower()
    op = str(rule.get("op") or ">=")
    return {
        ">=": left >= right,
        ">": left > right,
        "<=": left <= right,
        "<": left < right,
        "==": left == right,
        "!=": left != right,
    }.get(op, False)


def apply_constraint_mask(
    probs_row: np.ndarray,
    record: dict[str, Any],
    rules: list[dict[str, Any]],
    action_labels: list[str],
) -> tuple[np.ndarray, list[bool]]:
    mask = [True] * len(action_labels)
    index_of = {label: i for i, label in enumerate(action_labels)}
    for rule in rules:
        if not _rule_matches(record, rule):
            continue
        for label in rule.get("forbidden_actions") or []:
            idx = index_of.get(label)
            if idx is not None:
                mask[idx] = False
        required = [index_of[l] for l in (rule.get("required_actions") or []) if l in index_of]
        if required:
            for i in range(len(mask)):
                if i not in required:
                    mask[i] = False
    if not any(mask):
        mask[-1] = True
    masked = np.array(
        [probs_row[i] if mask[i] and i < len(probs_row) else -1e9 for i in range(len(mask))],
        dtype=np.float32,
    )
    return masked, mask


def execute_inference(
    sess: ort.InferenceSession,
    baseline_data: dict[str, Any],
    action_labels: list[str],
    obs_batch: np.ndarray,
    records: list[dict[str, Any]] | None = None,
    safety_rules: list[dict[str, Any]] | None = None,
) -> dict[str, Any]:
    if obs_batch.ndim == 1:
        obs_batch = np.expand_dims(obs_batch, axis=0)

    obs_batch = obs_batch.astype(np.float32)
    try:
        expected_dim = sess.get_inputs()[0].shape[1]
        if isinstance(expected_dim, int) and obs_batch.shape[1] != expected_dim:
            if obs_batch.shape[1] < expected_dim:
                pad = np.zeros((obs_batch.shape[0], expected_dim - obs_batch.shape[1]), dtype=np.float32)
                obs_batch = np.hstack([obs_batch, pad])
            else:
                obs_batch = obs_batch[:, :expected_dim]
    except Exception:
        pass

    raw_probs = sess.run(None, {"obs": obs_batch})[0]
    masks: list[list[bool] | None] = [None] * len(raw_probs)
    if safety_rules:
        if not records:
            raise ValueError(
                "This bundle declares hard constraints and cannot run blind. Supply the raw "
                "records via --record-json, or a 'records' list in the /predict request."
            )
        if len(records) != len(raw_probs):
            raise ValueError(
                f"Got {len(records)} raw record(s) for {len(raw_probs)} observation(s); "
                "they must be aligned one-to-one so the safety mask is applied to the right row."
            )
        masked_rows = []
        for row_index, (row, record) in enumerate(zip(raw_probs, records)):
            masked, mask = apply_constraint_mask(row, record, safety_rules, action_labels)
            masked_rows.append(masked)
            masks[row_index] = mask
        probs = np.vstack(masked_rows)
    else:
        probs = raw_probs

    predicted_actions = np.argmax(probs, axis=-1)
    raw_actions = np.argmax(raw_probs, axis=-1)

    predictions = []
    for idx, (p, a) in enumerate(zip(probs, predicted_actions)):
        lbl = action_labels[a] if a < len(action_labels) else f"action_{a}"
        entry = {
            "sample_idx": idx,
            "action_idx": int(a),
            "action_label": lbl,
            "probabilities": [float(val) for val in p],
        }
        if safety_rules:
            raw_idx = int(raw_actions[idx])
            entry.update({
                "raw_action_idx": raw_idx,
                "raw_action_label": (
                    action_labels[raw_idx] if raw_idx < len(action_labels) else f"action_{raw_idx}"
                ),
                "safety_override": bool(raw_idx != int(a)),
                "action_mask": masks[idx],
            })
        predictions.append(entry)

    # Drift check on the inference batch. This used to call a `detect_drift` method that does not
    # exist, inside a bare `except`, so an exported policy reported "healthy" for any input.
    drift_report = {"drift_detected": False, "psi_max": 0.0, "status": "unmonitored"}
    if baseline_data:
        try:
            from rl_ide.drift.monitor import DriftBaseline, DriftDetector

            detector = DriftDetector(DriftBaseline.load(baseline_data))
            sig = detector.check_drift(obs_batch, probs)
            drift_report = {
                "drift_detected": bool(sig.is_drifted),
                "psi_max": float(sig.max_psi),
                "status": "drifted" if sig.is_drifted else "healthy",
                "reasons": list(sig.reasons),
                "recommendation": sig.recommendation,
            }
        except Exception as exc:  # a bundle must still answer; say why it could not monitor
            drift_report["status"] = "unmonitored"
            drift_report["error"] = f"{type(exc).__name__}: {exc}"

    return {
        "predictions": predictions,
        "drift": drift_report,
        "batch_size": len(obs_batch),
    }


def print_cli_summary(res: dict[str, Any], n_samples: int):
    print("=" * 60)
    print(f"RL Policy Local Inference Complete: {n_samples} samples processed")
    print("=" * 60)
    print(f"Drift Status: {res.get('drift', {}).get('status', 'healthy').upper()} (PSI Max: {res.get('drift', {}).get('psi_max', 0.0):.3f})")
    print("-" * 60)
    print("Sample Predictions:")
    for pred in res["predictions"][:5]:
        print(f"  [#{pred['sample_idx']}] Action: {pred['action_label']} ({pred['action_idx']}) | Probs: {[round(x, 3) for x in pred['probabilities']]}")
    if len(res["predictions"]) > 5:
        print(f"  ... and {len(res['predictions']) - 5} more.")
    print("=" * 60)


class PolicyDaemonHandler(http.server.BaseHTTPRequestHandler):
    def do_GET(self):
        if self.path == "/health":
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.end_headers()
            self.wfile.write(json.dumps({"status": "healthy", "service": "v4.0 policy-daemon"}).encode("utf-8"))
        elif self.path == "/info":
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.end_headers()
            self.wfile.write(json.dumps({
                "action_labels": self.server.action_labels,
                "has_baseline": bool(self.server.baseline_data),
            }).encode("utf-8"))
        else:
            self.send_response(404)
            self.end_headers()

    def do_POST(self):
        if self.path == "/predict":
            content_len = int(self.headers.get("Content-Length", 0))
            body = self.rfile.read(content_len).decode("utf-8")
            try:
                data = json.loads(body)
                if "observations" in data:
                    obs = np.array(data["observations"], dtype=np.float32)
                elif "observation" in data:
                    obs = np.array(data["observation"], dtype=np.float32)
                else:
                    self.send_response(400)
                    self.send_header("Content-Type", "application/json")
                    self.end_headers()
                    self.wfile.write(json.dumps({"error": "Missing 'observations' or 'observation' key"}).encode("utf-8"))
                    return

                res = execute_inference(
                    self.server.sess,
                    self.server.baseline_data,
                    self.server.action_labels,
                    obs,
                    records=data.get("records"),
                    safety_rules=getattr(self.server, "safety_rules", []),
                )
                self.send_response(200)
                self.send_header("Content-Type", "application/json")
                self.end_headers()
                self.wfile.write(json.dumps(res).encode("utf-8"))
            except Exception as e:
                self.send_response(500)
                self.send_header("Content-Type", "application/json")
                self.end_headers()
                self.wfile.write(json.dumps({"error": str(e)}).encode("utf-8"))
        elif self.path == "/shutdown":
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.end_headers()
            self.wfile.write(json.dumps({"status": "shutting_down"}).encode("utf-8"))
            threading.Thread(target=self.server.shutdown).start()
        else:
            self.send_response(404)
            self.end_headers()


def run_daemon(bundle_dir: Path, host: str, port: int):
    sess, baseline_data, action_labels = load_bundle_context(bundle_dir)
    safety_rules = load_safety_rules(bundle_dir)
    server = http.server.HTTPServer((host, port), PolicyDaemonHandler)
    server.bundle_dir = bundle_dir
    server.sess = sess
    server.baseline_data = baseline_data
    server.action_labels = action_labels
    server.safety_rules = safety_rules

    print(f"Starting Policy Daemon on http://{host}:{port} ...")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\\nShutting down daemon.")
    finally:
        server.server_close()


